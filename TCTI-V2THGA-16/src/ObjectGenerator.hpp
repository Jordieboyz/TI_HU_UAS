#ifndef SRC_OBJECTGENERATOR_HPP_
#define SRC_OBJECTGENERATOR_HPP_

#include <cstdint>

#include "game-objects/GameObject.hpp"
#include "game-objects/GameObjectFactory.hpp"

struct GameData;

/** @file **/

class ObjectGenerator {
public:
	ObjectGenerator(const char *backGroundImage, GameData *apGameData);
	virtual ~ObjectGenerator();

	/**
	 * @brief
	 *  This method creates a new wall from map specified in constructor.
	 * @return
	 *  GameObject * if success, nullptr if nothing left to do.
	 */
	GameObject *generate_object(enum GAME_OBJECT_TYPE aeType, uint32_t au32Col);

private:
	/**
	 * @brief
	 *  Function that creates the actual object and makes sure match is not
	 *  found twice.
	 * @details
	 *  The function first gets the size of the found region by scanning
	 *  left to right and top to bottom. Next it clears pixels to keep us
	 *  from finding the same match twice. Finally it requests a new game-
	 *  object from the GameObjectFactoy, see GameObjectFactory.hpp for
	 *  details on the GAME_OBJECT_TYPE_ENUM.
	 * @param aiXpos Xpos of found match
	 * @param aiYpos Ypos of found match
	 * @param aeTypeToGen Type of object to be generated.
	 * @return gameobject generated by factory.
	 */
	GameObject *process_match(int aiXpos, int aiYpos,
			enum GAME_OBJECT_TYPE aeTypeToGen);

	unsigned  uIterator = 0;
	uint8_t *pImg;
	unsigned uLen;

	uint32_t u32Width;
	uint32_t u32Height;
	uint32_t *pPixels;

	uint32_t u32ColToSearch = 0;

	GameData *pGameData;
};

#endif /* SRC_OBJECTGENERATOR_HPP_ */
